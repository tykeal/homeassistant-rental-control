"""Recompile the hash-pinned, isolated authentic Keymaster import lock."""

from __future__ import annotations

from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory

_ROOT = Path(__file__).resolve().parents[1]
_UV_VERSION = "0.13.5"
_PYTHON_VERSION = (3, 14, 2)
_LOCK_PATH = _ROOT / "tests/fixtures/keymaster_import_probe.lock"
_HEADER = """\
# SPDX-FileCopyrightText: 2026 Andrew Grimberg <tykeal@bardicgrove.org>
# SPDX-License-Identifier: Apache-2.0
#
# Generated by scripts/update_keymaster_import_probe_lock.py with uv 0.13.5.
# Direct providers come from HA 2026.11.0 manifests; all packages are exact
# and SHA-256 pinned. Root uv.lock versions constrain compatible packages.
"""


def _run(command: list[str]) -> None:
    """Run one pinned uv command from the project root."""
    subprocess.run(command, cwd=_ROOT, check=True, stdout=subprocess.DEVNULL)


def main() -> None:
    """Export locked constraints and compile the isolated probe closure."""
    if sys.version_info[:3] != _PYTHON_VERSION:
        raise SystemExit("lock refresh requires CPython 3.14.2")
    uv_version = subprocess.run(
        ["uv", "--version"],
        cwd=_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.split()
    if len(uv_version) < 2 or uv_version[1] != _UV_VERSION:
        raise SystemExit(f"lock refresh requires uv {_UV_VERSION}")

    with TemporaryDirectory(prefix="rc-keymaster-lock-") as directory:
        temporary = Path(directory)
        constraints = temporary / "project-constraints.txt"
        resolved = temporary / "resolved-probe.txt"
        _run(
            [
                "uv",
                "export",
                "--locked",
                "--extra",
                "test",
                "--group",
                "dev",
                "--no-emit-project",
                "--no-hashes",
                "--no-annotate",
                "--format",
                "requirements-txt",
                "--output-file",
                str(constraints),
            ]
        )
        _run(
            [
                "uv",
                "pip",
                "compile",
                "--python-version",
                "3.14.2",
                "--python-platform",
                "x86_64-unknown-linux-gnu",
                "--constraint",
                str(constraints),
                "--generate-hashes",
                "--no-header",
                "--no-annotate",
                "--output-file",
                str(resolved),
                "tests/fixtures/keymaster_import_probe.in",
            ]
        )
        _LOCK_PATH.write_text(
            _HEADER + resolved.read_text(encoding="utf-8"),
            encoding="utf-8",
        )
    print(f"Updated {_LOCK_PATH.relative_to(_ROOT)}")


if __name__ == "__main__":
    main()
